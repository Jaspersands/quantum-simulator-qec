INF_DET_BEAM = 65535
_DEFAULT_SEED = 2384753
_MAX = 2**64 - 1


def suggest_sparsify_reactivate_limit(num_detectors: int, sparsify_base_degree: int) -> int:
    """The suggested number of optional high-degree errors to reactivate per shot."""
    return call(_core.suggest_sparsify_reactivate_limit, int(num_detectors), int(sparsify_base_degree))


def _nonnegative(value: Any, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, np.integer)) or value < 0 or value >= 2**64:
        raise ValueError(f"{name} must be a nonnegative integer.")
    return int(value)


def _c_float(value: Any, name: str) -> float:
    if isinstance(value, (str, bytes)) or not (hasattr(type(value), "__float__") or hasattr(type(value), "__index__")):
        raise TypeError(f"{name}: incompatible function arguments; expected a float, got {value!r}.")
    return float(value)


class _Field:
    """A configuration setting held as Tesseract's C++ field holds it: set through the
    conversion its binding makes (a ``TypeError`` for a value of the wrong kind)."""

    def __init__(self, convert: Any) -> None:
        self.convert = convert

    def __set_name__(self, owner: type, name: str) -> None:
        self.name, self.slot = name, "_" + name

    def __get__(self, obj: Any, owner: Any = None) -> Any:
        return self if obj is None else getattr(obj, self.slot)

    def __set__(self, obj: Any, value: Any) -> None:
        setattr(obj, self.slot, self.convert(value, self.name))


def _flag(value: Any, name: str) -> bool:
    return bool(value)


def _size_t(value: Any, name: str) -> int:
    return _int(value, name, 0, 2**64)


_C_INT = _int
_NO_MODEL = object()

# Tesseract's TesseractConfig takes its settings with no model (the first of its two
# constructors) or after one.
_SETTINGS = (
    ("det_beam", 5), ("beam_climbing", False), ("no_revisit_dets", True), ("verbose", False), ("merge_errors", True), ("pqlimit", 200000),
    ("det_orders", None), ("det_penalty", 0.0), ("create_visualization", False), ("sparsify_errors", False), ("sparsify_base_degree", -1),
    ("sparsify_max_degree", -1), ("sparsify_reactivate_limit", -1), ("num_det_orders", None), ("det_order_method", None), ("seed", None),
)


def _incompatible(args: Sequence[Any], kwargs: dict) -> TypeError:
    names = ", ".join(n for n, _ in _SETTINGS)
    given = ", ".join([repr(a) for a in args] + [f"{k}={v!r}" for k, v in kwargs.items()])
    return TypeError(
        "__init__(): incompatible constructor arguments. The following argument types are supported:\n"
        f"    1. TesseractConfig({names})\n    2. TesseractConfig(dem, {names})\n\nInvoked with: {given}"
    )


def _bind(params: Sequence[tuple], args: Sequence[Any], kwargs: dict) -> Optional[dict]:
    if len(args) > len(params):
        return None
    values = dict(params)
    for (name, _), a in zip(params, args):
        values[name] = a
    for k, v in kwargs.items():
        if k not in values or k in [n for n, _ in params[: len(args)]]:
            return None
        values[k] = v
    return values


def _is_int(value: Any) -> bool:
    return not isinstance(value, float) and hasattr(type(value), "__index__")


class TesseractConfig:
    """How a Tesseract decoder searches: the model, the beam (``det_beam`` lit detectors above
    the fewest seen; ``INF_DET_BEAM`` for none), beam climbing, skipping revisited detector
    patterns, the queue bound, the detector orders (literal ``det_orders``, or
    ``num_det_orders`` generated by ``det_order_method`` from ``seed``; 20 index orders from
    2384753 by default), a per-detector penalty, merging errors of one symptom, sparsified
    error activation and the visualizer log.

    As Tesseract's, it is made with the model first (``TesseractConfig(dem, det_beam=...)``)
    or with no model, the settings then starting at ``det_beam`` (``TesseractConfig(7)``).
    ``dem`` reads back as Stim's model when it was given as Stim's (and as this package's
    otherwise; Tesseract's is always Stim's), a copy each time it is read."""

    __slots__ = (
        "_dem", "_stims", "_orders", "_det_beam", "_beam_climbing", "_no_revisit_dets", "_verbose", "_merge_errors", "_pqlimit", "_det_penalty",
        "_create_visualization", "_sparsify_errors", "_sparsify_base_degree", "_sparsify_max_degree", "_sparsify_reactivate_limit",
    )

    det_beam = _Field(_C_INT)
    beam_climbing = _Field(_flag)
    no_revisit_dets = _Field(_flag)
    verbose = _Field(_flag)
    merge_errors = _Field(_flag)
    pqlimit = _Field(_size_t)
    det_penalty = _Field(_c_float)
    create_visualization = _Field(_flag)
    sparsify_errors = _Field(_flag)
    sparsify_base_degree = _Field(_C_INT)
    sparsify_max_degree = _Field(_C_INT)
    sparsify_reactivate_limit = _Field(_C_INT)

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        import stabilizer_qec as sq

        if "dem" not in kwargs and (not args or _is_int(args[0])):
            values = _bind(_SETTINGS, args, kwargs)
            dem: Any = _NO_MODEL
        else:
            values = _bind((("dem", _NO_MODEL),) + _SETTINGS, args, kwargs)
            dem = _NO_MODEL if values is None else values.pop("dem")
            if dem is _NO_MODEL:
                values = None
        if values is None:
            raise _incompatible(args, kwargs)
        try:
            for name in ("det_beam", "beam_climbing", "no_revisit_dets", "verbose", "merge_errors", "pqlimit", "det_penalty", "create_visualization",
                         "sparsify_errors", "sparsify_base_degree", "sparsify_max_degree", "sparsify_reactivate_limit"):
                setattr(self, name, values[name])
        except TypeError:
            raise _incompatible(args, kwargs) from None
        if dem is _NO_MODEL:
            self._dem, self._stims = sq.DetectorErrorModel(), False
        else:
            self.dem = dem
        det_orders, num_det_orders, det_order_method, seed = (values[k] for k in ("det_orders", "num_det_orders", "det_order_method", "seed"))
        literal = [] if det_orders is None else [[int(d) for d in order] for order in det_orders]
        generated = num_det_orders is not None or det_order_method is not None or seed is not None
        if literal and generated:
            raise ValueError("det_orders cannot be combined with num_det_orders, det_order_method, or seed.")
        if literal:
            # (Checked against the model when read or compiled, as Tesseract's are.)
            self._orders: tuple = ("literal", literal)
        else:
            count = 20 if num_det_orders is None else _nonnegative(num_det_orders, "num_det_orders")
            if count == 0:
                raise ValueError("num_det_orders must be at least 1 and fit in size_t.")
            if det_order_method is not None and not isinstance(det_order_method, DetectorOrderMethod):
                raise RuntimeError(f"Unable to cast Python instance of type {type(det_order_method)} to C++ type 'tesseract_decoder::DetectorOrder::Method'")
            method = DetectorOrderMethod.Index if det_order_method is None else det_order_method
            if method == DetectorOrderMethod.Literal:
                raise ValueError("Literal detector orders cannot be generated.")
            order_seed = _DEFAULT_SEED if seed is None else _nonnegative(seed, "seed")
            self._orders = ("generated", count, method, order_seed)

    @property
    def dem(self) -> Any:
        """The model: Stim's when it was given as Stim's, this package's otherwise (a copy)."""
        return _as_given(self._dem, self._stims) if self._stims else self._dem.copy()

    @dem.setter
    def dem(self, dem: Any) -> None:
        self._dem, self._stims = _dem(dem), _is_stims(dem)

    @property
    def det_orders(self) -> List[List[int]]:
        """The detector orders, resolved against the model: order[position] = detector."""
        if self._orders[0] == "literal":
            orders = self._orders[1]
            _validate_orders(orders, self._dem.num_detectors)
            return [list(o) for o in orders]
        _, count, method, seed = self._orders
        return _orders(self._dem, count, method, seed)

    @det_orders.setter
    def det_orders(self, orders: Sequence[Sequence[int]]) -> None:
        if orders is None or isinstance(orders, (str, bytes)):
            raise TypeError("det_orders: incompatible function arguments; expected a list of detector orders.")
        orders = [[int(d) for d in o] for o in orders]
        # (As Tesseract's does, an empty list goes back to the default generated orders, which
        # a decoder's configuration cannot resolve. Also as Tesseract's, the orders are checked
        # against the model when read or compiled, not here; a decoder checks them at its next
        # decode, where Tesseract would read past a short order.)
        self._orders = ("literal", orders) if orders else ("generated", 20, DetectorOrderMethod.Index, _DEFAULT_SEED)

    def __str__(self) -> str:
        n = len(self._orders[1]) if self._orders[0] == "literal" else self._orders[1]
        return (
            f"TesseractConfig(dem=DetectorErrorModel_Object, det_beam={self.det_beam}, no_revisit_dets={int(self.no_revisit_dets)}, "
            f"verbose={int(self.verbose)}, merge_errors={int(self.merge_errors)}, pqlimit={self.pqlimit}, num_detector_orders={n}, "
            f"det_penalty={self.det_penalty:g}, create_visualization={int(self.create_visualization)})"
        )

    def compile_decoder(self) -> "TesseractDecoder":
        return TesseractDecoder(self)

    def compile_decoder_for_dem(self, dem: Any) -> "TesseractDecoder":
        # (As Tesseract's does, this keeps ``dem`` as the configuration's model.)
        self.dem = dem
        return TesseractDecoder(self)


def _validate_orders(orders: Sequence[Sequence[int]], n: int) -> None:
    for order in orders:
        if len(order) != n:
            raise ValueError(f"Detector order has size {len(order)}, but the detector error model has {n} detectors.")
        seen = [False] * n
        for position, d in enumerate(order):
            if d >= n or d < 0:
                raise ValueError(f"Detector order contains out-of-range detector ID {d} at position {position}.")
            if seen[d]:
                raise ValueError(f"Detector order contains detector ID {d} more than once.")
            seen[d] = True


class _Decoder:
    """What Tesseract's and the simplex decoder share: the retained errors and their maps."""

    num_detectors: int
    num_observables: int

    def _prepare(self, dem: Any, merge_errors: bool) -> Any:
        flat, self._dem_to_error, self._error_to_dem = _retained_maps(dem, merge_errors)
        self.errors = [Error(inst) for inst in flat if inst.type == "error"]
        self.num_detectors = flat.num_detectors
        self.num_observables = flat.num_observables
        self.predicted_errors_buffer: List[int] = []
        return flat

    def _retained(self, dem_error: Any) -> int:
        dem_error = _size_t(dem_error, "predicted_errors")
        if dem_error >= len(self._dem_to_error):
            raise IndexError(f"vector::_M_range_check: __n (which is {dem_error}) >= this->size() (which is {len(self._dem_to_error)})")
        e = self._dem_to_error[dem_error]
        if e == _MAX:
            raise ValueError("error index does not map to a retained decoder error")
        return e

    def cost_from_errors(self, predicted_errors: Sequence[int]) -> float:
        """The total cost of errors given by their index in the flattened model."""
        total = 0.0
        for e in [self._retained(i) for i in predicted_errors]:
            total += self.errors[e].likelihood_cost
        return total

    def _flipped(self, predicted_errors: Sequence[int]) -> List[int]:
        flipped: set = set()
        for e in [self._retained(i) for i in predicted_errors]:
            flipped ^= set(self.errors[e].symptom._observables)
        return sorted(flipped)

    def get_observables_from_errors(self, predicted_errors: Sequence[int]) -> List[bool]:
        """Which observables the errors (by index in the flattened model) flip."""
        out = [False] * self.num_observables
        for o in self._flipped(predicted_errors):
            out[o] = not out[o]
        return out

    def _syndrome(self, syndrome: Any) -> List[int]:
        s = np.asarray(syndrome, dtype=bool)
        if s.ndim != 1:
            raise ValueError(f"array has incorrect number of dimensions: {s.ndim}; expected 1")
        if s.size != self.num_detectors:
            raise ValueError(f"Syndrome array size ({s.size}) does not match the number of detectors in the decoder ({self.num_detectors}).")
        return np.flatnonzero(s).tolist()

    def _observables(self) -> np.ndarray:
        out = np.zeros(self.num_observables, dtype=bool)
        for o in self._flipped(self.predicted_errors_buffer):
            out[o] ^= True
        return out

    def decode(self, syndrome: Any) -> np.ndarray:
        """Which observables one shot's syndrome (a bool per detector) flips."""
        with _redirected():
            self._decode(self._syndrome(syndrome))
        return self._observables()

    def decode_from_detection_events(self, detections: Sequence[int]) -> np.ndarray:
        """The same, from the indices of the detectors that fired."""
        events = [_size_t(d, "detections") for d in detections]
        with _redirected():
            self._decode(events)
        return self._observables()

    def decode_batch(self, syndromes: Any) -> np.ndarray:
        """Each row's observables."""
        rows = np.asarray(syndromes, dtype=bool)
        if rows.ndim != 2:
            raise RuntimeError("Input syndromes must be a 2D NumPy array.")
        if rows.shape[1] != self.num_detectors:
            raise ValueError(f"The number of detectors in the input array ({rows.shape[1]}) does not match the number of detectors in the decoder ({self.num_detectors}).")
        out = np.zeros((rows.shape[0], self.num_observables), dtype=bool)
        for i, row in enumerate(rows):
            self._decode(np.flatnonzero(row).tolist())
            out[i] = self._observables()
        return out

    def decode_to_errors(self, syndrome: Any, det_order: Any = None, det_beam: Any = None) -> List[int]:
        """The errors (by index in the flattened model) one shot's syndrome is decoded to;
        with ``det_order`` and ``det_beam``, by one search with that detector order and beam."""
        if (det_order is None) != (det_beam is None):
            raise TypeError("decode_to_errors takes both det_order and det_beam, or neither.")
        args = () if det_order is None else (det_order, det_beam)
        with _redirected():
            self._decode(self._syndrome(syndrome), *args)
        return list(self.predicted_errors_buffer)

    def _decode(self, detections: List[int], *args: Any) -> None:  # pragma: no cover - overridden
        raise NotImplementedError


_UNRESOLVED = "Detector order has not been resolved against a DEM."


class TesseractDecoder(_Decoder):
    """Tesseract's A* search for the most likely set of errors (Beni, Higgott and Shutty,
    2025). ``decode_to_errors`` gives the errors (by index in the flattened model, the first of
    a merged group), ``predicted_errors_buffer`` keeps them, ``low_confidence_flag`` says whether
    every search gave up, and ``errors`` lists the errors searched over (merged, those of
    probability 0 dropped).

    As Tesseract's, ``config`` is the decoder's own configuration, read at every decode: a
    change to its beam, beam climbing, revisiting, queue bound, detector penalty, detector
    orders, ``verbose`` or ``create_visualization`` applies to the next decode (the model,
    merging and sparsifying stay as the decoder was made). Assigning ``config`` copies in a
    configuration whose detector orders are literal, and refuses one whose orders are still
    to be generated, as Tesseract's does."""

    def __init__(self, config: TesseractConfig) -> None:
        if config._orders[0] == "literal" and not config._orders[1]:
            raise ValueError("At least one detector order is required.")
        flat = self._prepare(config._dem, config.merge_errors)
        orders = config.det_orders if config._orders[0] == "literal" else _orders(flat, config._orders[1], config._orders[2], config._orders[3])
        _validate_orders(orders, flat.num_detectors)
        self._config = copy.copy(config)
        self._config._dem = flat
        self._config._orders = ("literal", orders)
        self._sparsify = None
        if config.sparsify_errors:
            self._sparsify = (config.sparsify_base_degree, config.sparsify_max_degree, config.sparsify_reactivate_limit)
            if config.sparsify_reactivate_limit == -1 and config.sparsify_base_degree > 0:
                # Tesseract keeps the limit it suggests, capped at the number of errors.
                n, cap = flat.num_detectors, min(len(self.errors), 2**31 - 1)
                self._config.sparsify_reactivate_limit = 0 if n == 0 or cap <= 0 else min(suggest_sparsify_reactivate_limit(n, config.sparsify_base_degree), cap)
        if config.verbose:
            _cout(self.errors)
        self._flat = flat
        self._build()
        self.low_confidence_flag = False
        self.visualizer = Visualizer()
        if config.create_visualization:
            self.visualizer._add_detector_coords(get_detector_coords(flat))
            self.visualizer._add_errors(self.errors)

    def _settings(self) -> tuple:
        c = self._config
        return (c.det_beam, c.beam_climbing, c.no_revisit_dets, c.pqlimit, c.det_penalty, c._orders)

    def _search_args(self) -> tuple:
        c = self._config
        # Tesseract adds the beam to a size_t, so a negative one wraps as it does there.
        return c.det_beam % 2**64, c.beam_climbing, c.no_revisit_dets, None if c.pqlimit >= 2**63 else c.pqlimit, c._orders[1], c.det_penalty

    def _build(self) -> None:
        c = self._config
        beam, climbing, no_revisit, pqlimit, orders, penalty = self._search_args()
        self._x = call(
            _core.DemSearch, self._flat._d, beam, climbing, no_revisit, pqlimit, orders, 1, "index", 0,
            penalty, False, "native", self._sparsify, c.create_visualization, c.verbose,
        )
        self._built = (self._settings(), c.verbose, c.create_visualization)

    def _sync(self) -> None:
        """Bring the search up to date with the configuration, as Tesseract reads its config
        at every decode."""
        c = self._config
        if c._orders[0] != "literal":
            raise RuntimeError(_UNRESOLVED)
        settings, verbose, viz = self._built
        changed = self._settings()
        # (The orders are compared by identity: assigning them makes a new tuple.)
        if (c.verbose, c.create_visualization) != (verbose, viz):
            _validate_orders(c._orders[1], self.num_detectors)
            self._build()
        elif changed[:5] != settings[:5] or changed[5] is not settings[5]:
            _validate_orders(c._orders[1], self.num_detectors)
            call(self._x.reconfigure, *self._search_args())
            self._built = (changed, verbose, viz)

    @property
    def config(self) -> TesseractConfig:
        """The decoder's configuration (its own: changes to it apply from the next decode)."""
        return self._config

    @config.setter
    def config(self, config: TesseractConfig) -> None:
        if not isinstance(config, TesseractConfig):
            raise TypeError(f"config: incompatible function arguments; expected a TesseractConfig, got {type(config).__name__}.")
        # (Generated orders are taken; as in Tesseract, the next decode refuses them.)
        self._config = copy.copy(config)

    def _decode_result(self, detections: List[int], updates: Sequence[Any] = ()) -> tuple:
        """Tesseract's ``decode_result``, with some errors' probabilities (by index in the
        flattened model) changed for this decode only: (observables flipped, errors found,
        whether every search gave up, their cost under the changed probabilities)."""
        if not updates:
            self._decode(detections)
            return self._flipped(self.predicted_errors_buffer), list(self.predicted_errors_buffer), self.low_confidence_flag, self.cost_from_errors(self.predicted_errors_buffer)
        # The search's model is the retained one, so each update's index in the flattened
        # model goes through the map to the retained error it went into.
        retained = []
        for i, p in updates:
            i, n = int(i), len(self._dem_to_error)
            if i < 0 or i >= n:
                raise ValueError(f"DEM error index {i} is out of range for {n} DEM errors.")
            if self._dem_to_error[i] == _MAX:
                raise ValueError(f"DEM error index {i} was removed from the decoder.")
            retained.append((self._dem_to_error[i], float(p)))
        self._sync()
        faults, low, cost = call(self._x.decode_with_probabilities, detections, retained)
        self._finish(faults, low)
        return self._flipped(self.predicted_errors_buffer), list(self.predicted_errors_buffer), self.low_confidence_flag, cost

    def _decode(self, detections: List[int], *args: Any) -> None:
        self._sync()
        if args:
            det_order, det_beam = (int(a) for a in args)
            if det_order < 0 or det_beam < 0:
                raise TypeError("det_order and det_beam must be nonnegative integers.")
            if det_order >= len(self._config._orders[1]):
                raise IndexError(f"vector::_M_range_check: __n (which is {det_order}) >= this->size() (which is {len(self._config._orders[1])})")
            faults, low = call(self._x.decode_once, detections, det_order, det_beam % 2**64)
        else:
            for d in detections:
                if d >= self.num_detectors:
                    raise RuntimeError(f"Symptom {d} references a detector >= num_detectors (= {self.num_detectors}).")
            faults, low = call(self._x.decode_to_faults, detections)
        self._finish(faults, low)

    def _finish(self, faults: List[int], low: bool) -> None:
        self.predicted_errors_buffer = [self._error_to_dem[f] for f in faults]
        self.low_confidence_flag = bool(low)
        if self._config.create_visualization:
            self.visualizer.lines.extend(self._x.take_trace())
        if self._config.verbose:
            _cout(self._x.take_log())
