_FIELDS = (
    "det_beam", "beam_climbing", "no_revisit_dets", "verbose", "merge_errors", "pqlimit", "det_penalty", "create_visualization",
    "sparsify_errors", "sparsify_base_degree", "sparsify_max_degree", "sparsify_reactivate_limit", "num_det_orders", "det_order_method", "seed",
)


def _pack(decoder: TesseractDecoder, rows: np.ndarray, num_detectors: int, num_observables: int, discard: bool) -> np.ndarray:
    """Each shot's predicted observables, bit packed (and, with ``discard``, a byte that is 1
    where the search gave up), as Tesseract's sinter adapters write them."""
    nob = (num_observables + 7) // 8
    out = np.zeros((rows.shape[0], nob + int(discard)), dtype=np.uint8)
    for shot in range(rows.shape[0]):
        lit = np.flatnonzero(np.unpackbits(rows[shot], bitorder="little")[:num_detectors]).tolist()
        predictions, _, low, _ = decoder._decode_result(lit)
        for o in predictions:
            out[shot, o // 8] ^= 1 << (o % 8)
        if discard:
            out[shot, nob] = int(low)
    return out


def _rows(data: Any, num_detectors: int) -> np.ndarray:
    rows = np.asarray(data, dtype=np.uint8)
    if rows.ndim != 2:
        raise ValueError("Input `bit_packed_detection_event_data` must be a 2D array.")
    if rows.shape[1] != (num_detectors + 7) // 8:
        raise ValueError("Input array's second dimension does not match num_detector_bytes.")
    return rows


class TesseractSinterCompiledDecoder:
    """A Tesseract decoder for one model, for sinter."""

    def __init__(self, decoder: TesseractDecoder, num_detectors: int, num_observables: int) -> None:
        self._decoder = decoder
        self.num_detectors = num_detectors
        self.num_observables = num_observables

    @property
    def decoder(self) -> TesseractDecoder:
        """The Tesseract decoder."""
        return self._decoder

    def decode_shots_bit_packed(self, *, bit_packed_detection_event_data: Any) -> np.ndarray:
        """Each shot's predicted observables, bit packed, from its bit-packed detection events."""
        return _pack(self._decoder, _rows(bit_packed_detection_event_data, self.num_detectors), self.num_detectors, self.num_observables, False)


class TesseractSinterDecoder:
    """Makes Tesseract decoders for sinter: Tesseract's settings, with ``num_det_orders``
    detector orders generated by ``det_order_method`` from ``seed``."""

    def __init__(
        self,
        det_beam: int = 5,
        beam_climbing: bool = False,
        no_revisit_dets: bool = True,
        verbose: bool = False,
        merge_errors: bool = True,
        pqlimit: int = 200000,
        det_penalty: float = 0.0,
        create_visualization: bool = False,
        num_det_orders: int = 1,
        det_order_method: Any = DetectorOrderMethod.Index,
        seed: int = 0,
        sparsify_errors: bool = False,
        sparsify_base_degree: int = -1,
        sparsify_max_degree: int = -1,
        sparsify_reactivate_limit: int = -1,
    ) -> None:
        if isinstance(num_det_orders, bool) or int(num_det_orders) < 0 or int(seed) < 0 or int(pqlimit) < 0:
            raise TypeError("num_det_orders, seed and pqlimit must be nonnegative integers.")
        if int(num_det_orders) == 0:
            raise ValueError("num_det_orders must be at least 1.")
        self.det_beam = int(det_beam)
        self.beam_climbing = bool(beam_climbing)
        self.no_revisit_dets = bool(no_revisit_dets)
        self.verbose = bool(verbose)
        self.merge_errors = bool(merge_errors)
        self.pqlimit = int(pqlimit)
        self.det_penalty = float(det_penalty)
        self.create_visualization = bool(create_visualization)
        self.num_det_orders = int(num_det_orders)
        self.det_order_method = DetectorOrderMethod(int(det_order_method))
        self.seed = int(seed)
        self.sparsify_errors = bool(sparsify_errors)
        self.sparsify_base_degree = int(sparsify_base_degree)
        self.sparsify_max_degree = int(sparsify_max_degree)
        self.sparsify_reactivate_limit = int(sparsify_reactivate_limit)

    def _state(self) -> tuple:
        return tuple(getattr(self, f) for f in _FIELDS)

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, TesseractSinterDecoder):
            return NotImplemented
        return self._state() == other._state()

    def __ne__(self, other: object) -> bool:
        eq = self.__eq__(other)
        return eq if eq is NotImplemented else not eq

    __hash__ = None  # type: ignore[assignment]

    def __getstate__(self) -> tuple:
        return (
            self.det_beam, self.beam_climbing, self.no_revisit_dets, self.verbose, self.merge_errors, self.pqlimit, self.det_penalty,
            self.create_visualization, self.num_det_orders, self.det_order_method, self.seed, self.sparsify_errors,
            self.sparsify_base_degree, self.sparsify_max_degree, self.sparsify_reactivate_limit,
        )

    def __setstate__(self, t: tuple) -> None:
        if len(t) == 11:
            args = list(t) + [False, -1, -1, -1]
        elif len(t) == 15:
            if isinstance(t[8], (bool, np.bool_)):
                # (The layout with the sparsify settings before the order settings.)
                args = list(t[:8]) + [t[12], t[13], t[14], t[8], t[9], t[10], t[11]]
            else:
                args = list(t)
        else:
            raise RuntimeError("Invalid state for TesseractSinterDecoder!")
        if int(args[8]) == 0:
            args[8], args[9], args[10] = 1, DetectorOrderMethod.Index, 0
        self.__init__(*args)  # type: ignore[misc]

    def _config(self, dem: Any) -> TesseractConfig:
        return TesseractConfig(
            dem, det_beam=self.det_beam, beam_climbing=self.beam_climbing, no_revisit_dets=self.no_revisit_dets, verbose=self.verbose,
            merge_errors=self.merge_errors, pqlimit=self.pqlimit, det_penalty=self.det_penalty, create_visualization=self.create_visualization,
            sparsify_errors=self.sparsify_errors, sparsify_base_degree=self.sparsify_base_degree, sparsify_max_degree=self.sparsify_max_degree,
            sparsify_reactivate_limit=self.sparsify_reactivate_limit, num_det_orders=self.num_det_orders,
            det_order_method=self.det_order_method, seed=self.seed,
        )

    def compile_decoder_for_dem(self, *, dem: Any) -> TesseractSinterCompiledDecoder:
        """A decoder for the model ``dem``."""
        model = _dem(dem)
        return TesseractSinterCompiledDecoder(TesseractDecoder(self._config(model)), model.num_detectors, model.num_observables)

    def decode_via_files(self, *, num_shots: int, num_dets: int, num_obs: int, dem_path: Any, dets_b8_in_path: Any, obs_predictions_b8_out_path: Any, tmp_dir: Any) -> None:
        """Decode bit-packed detection events read from a file, writing the predicted
        observables to another (sinter's file protocol)."""
        import stabilizer_qec as sq

        try:
            text = pathlib.Path(str(dem_path)).read_text()
        except OSError:
            raise RuntimeError(f"Failed to open DEM file: {dem_path}") from None
        decoder = TesseractDecoder(self._config(sq.DetectorErrorModel(text)))
        nd = (int(num_dets) + 7) // 8
        try:
            raw = pathlib.Path(str(dets_b8_in_path)).read_bytes()
        except OSError:
            raise RuntimeError(f"Failed to open input file: {dets_b8_in_path}") from None
        if len(raw) < int(num_shots) * nd:
            raise RuntimeError("Failed to read a full shot from the input file.")
        rows = np.frombuffer(raw[: int(num_shots) * nd], dtype=np.uint8).reshape(int(num_shots), nd)
        out = _pack(decoder, rows, int(num_dets), int(num_obs), False)
        pathlib.Path(str(obs_predictions_b8_out_path)).write_bytes(out.tobytes())


def make_tesseract_sinter_decoders_dict() -> Dict[str, TesseractSinterDecoder]:
    """Tesseract's sinter decoders by name."""
    long = dict(det_beam=20, beam_climbing=True, no_revisit_dets=True, pqlimit=1000000, num_det_orders=21, seed=2384753)
    short = dict(det_beam=15, beam_climbing=True, no_revisit_dets=True, pqlimit=200000, num_det_orders=16, seed=2384753)
    result: Dict[str, TesseractSinterDecoder] = {}
    result["tesseract-long-beam"] = TesseractSinterDecoder(**long)
    result["tesseract"] = result["tesseract-long-beam"]
    result["tesseract-long-beam-sparsify-color-code-like"] = TesseractSinterDecoder(**long, sparsify_errors=True, sparsify_base_degree=3)
    result["tesseract-long-beam-sparsify-surface-code-like"] = TesseractSinterDecoder(**long, sparsify_errors=True, sparsify_base_degree=2)
    result["tesseract-short-beam"] = TesseractSinterDecoder(**short)
    result["tesseract-short-beam-sparsify-color-code-like"] = TesseractSinterDecoder(**short, sparsify_errors=True, sparsify_base_degree=3)
    result["tesseract-short-beam-sparsify-surface-code-like"] = TesseractSinterDecoder(**short, sparsify_errors=True, sparsify_base_degree=2)
    return result
