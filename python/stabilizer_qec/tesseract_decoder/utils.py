__all__ = ["BFS", "Coordinate", "DetBFS", "DetCoordinate", "DetIndex", "DetOrder", "DetectorOrderMethod", "EPSILON", "INF", "Index", "Literal", "build_det_orders", "build_detector_graph", "get_detector_coords", "get_errors_from_dem"]

EPSILON = 1e-7
INF = math.inf


class _Enum:
    """An enumeration as pybind11 binds a C++ enum, as Tesseract's are: members compare equal
    to members of the same value only (not to ints), convert with ``int``, are not ordered,
    and any value of a C ``int`` makes one (named ``???`` when no member has it)."""

    __slots__ = ("_value",)
    _entries: Tuple[Tuple[str, int], ...] = ()

    def __init__(self, value: Any) -> None:
        if isinstance(value, float) or not hasattr(type(value), "__index__") or not -(2**31) <= value.__index__() < 2**31:
            raise TypeError(
                "__init__(): incompatible constructor arguments. The following argument types are supported:\n"
                f"    1. {type(self).__module__}.{type(self).__name__}(value: typing.SupportsInt)\n\nInvoked with: {value!r}"
            )
        self._value = value.__index__()

    def __init_subclass__(cls, **kwargs: Any) -> None:
        super().__init_subclass__(**kwargs)
        names = "\n\n".join(f"  {name}" for name, _ in cls._entries)
        cls.__doc__ = f"{cls.__doc__}\n\nMembers:\n\n{names}"
        for name, value in cls._entries:
            setattr(cls, name, cls(value))

    @property
    def name(self) -> str:
        return next((name for name, value in self._entries if value == self._value), "???")

    @property
    def value(self) -> int:
        return self._value

    def __int__(self) -> int:
        return self._value

    def __index__(self) -> int:
        return self._value

    def __eq__(self, other: object) -> bool:
        return type(other) is type(self) and other._value == self._value  # type: ignore[attr-defined]

    def __ne__(self, other: object) -> bool:
        return not self == other

    def __hash__(self) -> int:
        return hash(self._value)

    def __repr__(self) -> str:
        return f"<{type(self).__name__}.{self.name}: {self._value}>"

    def __str__(self) -> str:
        return f"{type(self).__name__}.{self.name}"

    def __getstate__(self) -> int:
        return self._value

    def __setstate__(self, state: int) -> None:
        self._value = int(state)


class _EnumType(type):
    @property
    def __members__(cls) -> Dict[str, Any]:
        return {name: getattr(cls, name) for name, _ in cls._entries}


class DetectorOrderMethod(_Enum, metaclass=_EnumType):
    """Detector ordering methods"""

    __slots__ = ()
    _entries = (
        ("BFS", 0), ("Index", 1), ("Coordinate", 2), ("Literal", 3), ("DetBFS", 0), ("DetIndex", 1), ("DetCoordinate", 2),
    )


DetOrder = DetectorOrderMethod
BFS, Index, Coordinate, Literal = DetectorOrderMethod.BFS, DetectorOrderMethod.Index, DetectorOrderMethod.Coordinate, DetectorOrderMethod.Literal
DetBFS, DetIndex, DetCoordinate = DetectorOrderMethod.DetBFS, DetectorOrderMethod.DetIndex, DetectorOrderMethod.DetCoordinate

_METHOD_NAMES = {0: "bfs", 1: "index", 2: "coordinate"}


def _orders(dem: Any, count: int, method: Any, seed: int) -> List[List[int]]:
    m = DetectorOrderMethod(int(method))
    if m == DetectorOrderMethod.Literal:
        raise ValueError("Literal detector orders cannot be generated.")
    if int(m) not in _METHOD_NAMES:
        raise ValueError("Unknown detector order method.")
    if count == 0:
        raise ValueError("The number of detector orders must be at least 1.")
    return [list(o) for o in call(_core.search_orders, _dem(dem)._d, int(count), _METHOD_NAMES[int(m)], int(seed) % 2**64, "native")]


def build_det_orders(dem: Any, num_det_orders: int, method: Any = DetectorOrderMethod.Index, seed: int = 0) -> List[List[int]]:
    """``num_det_orders`` detector traversal orders, order ``i`` generated by ``method`` (a
    ``DetectorOrderMethod``) from seed ``seed + i``."""
    count, seed = _int(num_det_orders, "num_det_orders", 0, 2**64), _int(seed, "seed", 0, 2**64)
    if not isinstance(method, DetectorOrderMethod):
        raise TypeError(f"build_det_orders(): incompatible function arguments; method must be a DetectorOrderMethod, not {type(method).__name__}.")
    return _orders(dem, count, method, seed)


def build_detector_graph(dem: Any) -> List[List[int]]:
    """Each detector's neighbours: the detectors it shares an error of nonzero probability
    with, sorted."""
    flat = _flat(dem)
    for inst in flat:
        if inst.type == "error" and inst.args_copy()[0] < 0:
            raise ValueError("Detector error probability must be non-negative.")
    return [list(n) for n in call(_core.search_detector_graph, flat._d)]


def get_detector_coords(dem: Any) -> List[List[float]]:
    """Each detector's coordinates (from its first DETECTOR instruction; none if it has none),
    or an empty list when the model declares no detectors."""
    flat = _flat(dem)
    n = flat.num_detectors
    coords: List[List[float]] = [[] for _ in range(n)]
    seen = [False] * n
    any_instruction = False
    for inst in flat:
        if inst.type == "detector":
            any_instruction = True
            args = [float(a) for a in inst.args_copy()]
            for t in inst.targets_copy():
                if t.is_relative_detector_id() and t.val < n and not seen[t.val]:
                    coords[t.val] = list(args)
                    seen[t.val] = True
        elif inst.type not in ("error", "logical_observable"):
            raise ValueError("Unexpected DemInstructionType found in the detector error model.")
    return coords if any_instruction else []


def get_errors_from_dem(dem: Any) -> List[Error]:
    """The model's errors of nonzero probability (its top-level instructions, as Tesseract
    reads them)."""
    return list(_iter_errors(dem))
