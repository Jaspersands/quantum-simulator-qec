"""Tesseract's detector orders and model helpers (``tesseract_decoder.utils``). Generated orders
are Tesseract's exactly: drawn from ``std::mt19937_64`` through the platform C++ library's
distributions, as Tesseract's build for this platform draws them."""

from __future__ import annotations

import enum
import math
from typing import Any, List

from .. import _core
from .._util import call
from .common import Error, _dem, _flat, _iter_errors

__all__ = ["BFS", "Coordinate", "DetBFS", "DetCoordinate", "DetIndex", "DetOrder", "DetectorOrderMethod", "EPSILON", "INF", "Index", "Literal", "build_det_orders", "build_detector_graph", "get_detector_coords", "get_errors_from_dem"]

EPSILON = 1e-7
INF = math.inf


class DetectorOrderMethod(enum.IntEnum):
    """Detector ordering methods."""

    BFS = 0
    Index = 1
    Coordinate = 2
    Literal = 3
    DetBFS = 0
    DetIndex = 1
    DetCoordinate = 2

    def __str__(self) -> str:
        return f"DetectorOrderMethod.{self.name}"


DetOrder = DetectorOrderMethod
BFS, Index, Coordinate, Literal = DetectorOrderMethod.BFS, DetectorOrderMethod.Index, DetectorOrderMethod.Coordinate, DetectorOrderMethod.Literal
DetBFS, DetIndex, DetCoordinate = DetectorOrderMethod.DetBFS, DetectorOrderMethod.DetIndex, DetectorOrderMethod.DetCoordinate

_METHOD_NAMES = {0: "bfs", 1: "index", 2: "coordinate"}


def _orders(dem: Any, count: int, method: Any, seed: int) -> List[List[int]]:
    m = DetectorOrderMethod(int(method))
    if m == DetectorOrderMethod.Literal:
        raise ValueError("Literal detector orders cannot be generated.")
    if count == 0:
        raise ValueError("The number of detector orders must be at least 1.")
    return [list(o) for o in call(_core.search_orders, _dem(dem)._d, int(count), _METHOD_NAMES[int(m)], int(seed) % 2**64, "native")]


def build_det_orders(dem: Any, num_det_orders: int, method: Any = DetectorOrderMethod.Index, seed: int = 0) -> List[List[int]]:
    """``num_det_orders`` detector traversal orders, order ``i`` generated by ``method`` from
    seed ``seed + i``."""
    return _orders(dem, num_det_orders, method, seed)


def build_detector_graph(dem: Any) -> List[List[int]]:
    """Each detector's neighbours: the detectors it shares an error of nonzero probability
    with, sorted."""
    flat = _flat(dem)
    for inst in flat:
        if inst.type == "error" and inst.args_copy()[0] < 0:
            raise ValueError("Detector error probability must be non-negative.")
    return [list(n) for n in call(_core.search_detector_graph, flat._d)]


def get_detector_coords(dem: Any) -> List[List[float]]:
    """Each detector's coordinates (from its first DETECTOR instruction; none if it has none),
    or an empty list when the model declares no detectors."""
    flat = _flat(dem)
    n = flat.num_detectors
    coords: List[List[float]] = [[] for _ in range(n)]
    seen = [False] * n
    any_instruction = False
    for inst in flat:
        if inst.type == "detector":
            any_instruction = True
            args = [float(a) for a in inst.args_copy()]
            for t in inst.targets_copy():
                if t.is_relative_detector_id() and t.val < n and not seen[t.val]:
                    coords[t.val] = list(args)
                    seen[t.val] = True
        elif inst.type not in ("error", "logical_observable"):
            raise ValueError("Unexpected DemInstructionType found in the detector error model.")
    return coords if any_instruction else []


def get_errors_from_dem(dem: Any) -> List[Error]:
    """The model's errors of nonzero probability (its top-level instructions, as Tesseract
    reads them)."""
    return list(_iter_errors(dem))
