"""The site editor's examples and its format fixtures, from the package.

    python tools/editor_fixtures.py

Writes `js/editor-examples.js` (circuits the editor offers, as flattened Stim text) and
`tests/editor_port/crumble.json` (each example's Stim text and the Crumble URL
`Circuit.to_crumble_url` writes for it, with and without markers): `tools/site-tests.mjs` checks
that the editor's JavaScript writes the same URLs and reads them back to the same circuits, and
`tests/test_editor_port.py` that the fixture is what the package writes.
"""

from __future__ import annotations

import json
import pathlib
import sys

import stabilizer_qec as sq

ROOT = pathlib.Path(__file__).resolve().parent.parent


def examples() -> dict:
    # A Bell pair made and unmade: every outcome deterministic, so the engine's detector sampler
    # and the editor's markers agree on what an error flips (a nondeterministic record would be
    # a coin flip here, where Stim's frame simulator pins it to its reference sample).
    bell = sq.Circuit("QUBIT_COORDS(0, 0) 0\nQUBIT_COORDS(1, 0) 1\nR 0 1\nTICK\nH 0\nTICK\nCX 0 1\nTICK\nCX 0 1\nTICK\nH 0\nTICK\nM 0 1\nDETECTOR(0, 0, 0) rec[-2]\nDETECTOR(1, 0, 0) rec[-1]\nOBSERVABLE_INCLUDE(0) rec[-1]")
    rep = sq.Circuit.generated("repetition_code:memory", distance=3, rounds=2).flattened()
    surface = sq.Circuit.generated("surface_code:rotated_memory_z", distance=3, rounds=1).flattened()
    color = sq.Circuit.generated("color_code:memory_xyz", distance=3, rounds=2).flattened()
    noisy = sq.memory_circuit(distance=3, rounds=2, p=0.01).flattened()
    return {
        "Bell pair": bell,
        "Repetition code, d = 3, 2 rounds": rep,
        "Surface code, d = 3, one round": surface,
        "Colour code, d = 3, 2 rounds": color,
        "Surface code with noise, d = 3, 2 rounds": noisy,
    }


def propagation_cases(c: sq.Circuit) -> list:
    """What a Pauli placed before each layer on each qubit flips, by the engine: the circuit with
    `X_ERROR(1)` (or `Z_ERROR(1)`) inserted at the start of the layer, sampled once (noiseless
    circuits only; their detectors are deterministic). The editor's marker propagation must
    agree."""
    text = str(c)
    if "ERROR" in text or "DEPOLARIZE" in text or "M(" in text:
        return []
    lines = text.split("\n")
    coords_end = max((i + 1 for i, l in enumerate(lines) if l.startswith("QUBIT_COORDS")), default=0)
    starts = [coords_end] + [i + 1 for i, l in enumerate(lines) if l.strip() == "TICK"]
    qubits = sorted({int(t) for l in lines for t in l.split()[1:] if t.isdigit()} if lines else set())
    cases = []
    for layer, at in enumerate(starts):
        for q in qubits:
            for pauli in ("X", "Z"):
                noisy = lines[:at] + [f"{pauli}_ERROR(1) {q}"] + lines[at:]
                cc = sq.Circuit("\n".join(noisy))
                dets, obs = cc.compile_detector_sampler(seed=1).sample(1, separate_observables=True)
                cases.append({"layer": layer, "qubit": q, "pauli": pauli, "detectors": [int(i) for i in dets[0].nonzero()[0]], "observables": [int(i) for i in obs[0].nonzero()[0]]})
    return cases


def main() -> int:
    fixtures = []
    for name, c in examples().items():
        entry = {"name": name, "stim": str(c), "url": c.to_crumble_url(), "num_detectors": c.num_detectors, "num_observables": c.num_observables, "cases": propagation_cases(c)}
        fixtures.append(entry)
    (ROOT / "tests" / "editor_port").mkdir(exist_ok=True)
    (ROOT / "tests" / "editor_port" / "crumble.json").write_text(json.dumps(fixtures, indent=1) + "\n")
    js = ["// Generated by tools/editor_fixtures.py from the package's circuits; do not edit.", "export const EXAMPLES = {"]
    for f in fixtures:
        js.append(f"  {json.dumps(f['name'])}: {json.dumps(f['stim'])},")
    js.append("};")
    (ROOT / "js" / "editor-examples.js").write_text("\n".join(js) + "\n")
    print(f"wrote {len(fixtures)} examples")
    return 0


if __name__ == "__main__":
    sys.exit(main())
